    <script>
        const form = document.getElementById('mfaForm');
        const codeBoxes = Array.from(
            document.querySelectorAll('.code-box')
        );
        const verificationCode = document.getElementById(
            'verification_code'
        );

        // Allow the user to enter one digit in each box.
        codeBoxes.forEach((box, index) => {

            box.addEventListener('input', function () {
                let value = this.value.replace(/\D/g, '');

                // Support pasting a complete six-digit code.
                if (value.length > 1) {
                    const digits = value.slice(0, 6).split('');

                    codeBoxes.forEach((input, i) => {
                        input.value = digits[i] || '';
                    });

                    const nextEmpty = codeBoxes.find(
                        input => input.value === ''
                    );

                    if (nextEmpty) {
                        nextEmpty.focus();
                    } else {
                        codeBoxes[5].focus();
                    }

                    return;
                }

                this.value = value;

                // Automatically move to the next box.
                if (value !== '' && index < codeBoxes.length - 1) {
                    codeBoxes[index + 1].focus();
                }
            });

            box.addEventListener('keydown', function (event) {

                // Move backwards when pressing Backspace on an empty box.
                if (
                    event.key === 'Backspace' &&
                    this.value === '' &&
                    index > 0
                ) {
                    codeBoxes[index - 1].focus();
                }

                // Allow left and right arrow navigation.
                if (
                    event.key === 'ArrowLeft' &&
                    index > 0
                ) {
                    event.preventDefault();
                    codeBoxes[index - 1].focus();
                }

                if (
                    event.key === 'ArrowRight' &&
                    index < codeBoxes.length - 1
                ) {
                    event.preventDefault();
                    codeBoxes[index + 1].focus();
                }
            });

            // Handle pasting a code into any of the boxes.
            box.addEventListener('paste', function (event) {
                event.preventDefault();

                const pastedText = (
                    event.clipboardData || window.clipboardData
                ).getData('text');

                const digits = pastedText
                    .replace(/\D/g, '')
                    .slice(0, 6)
                    .split('');

                codeBoxes.forEach((input, i) => {
                    input.value = digits[i] || '';
                });

                const nextEmpty = codeBoxes.find(
                    input => input.value === ''
                );

                if (nextEmpty) {
                    nextEmpty.focus();
                } else {
                    codeBoxes[5].focus();
                }
            });
        });

        // Combine all six digits before submitting the form.
        form.addEventListener('submit', function (event) {

            const code = codeBoxes
                .map(input => input.value)
                .join('');

            if (!/^\d{6}$/.test(code)) {
                event.preventDefault();

                const firstEmpty = codeBoxes.find(
                    input => input.value === ''
                );

                if (firstEmpty) {
                    firstEmpty.focus();
                }

                return;
            }

            verificationCode.value = code;
        });

        // Focus the first box when the page opens.
        codeBoxes[0].focus();
    </script>

</body>
