<?php
session_start();

require_once __DIR__ . '/config/database.php';
require_once __DIR__ . '/vendor/autoload.php';

use RobThree\Auth\TwoFactorAuth;
use RobThree\Auth\Providers\Qr\BaconQrCodeProvider;

// Only users with a pending login may verify MFA.
if (
    !isset(
        $_SESSION['pending_mfa_user_id'],
        $_SESSION['pending_mfa_role']
    ) ||
    !in_array(
        $_SESSION['pending_mfa_role'],
        ['student', 'lecturer', 'admin'],
        true
    )
) {
    header('Location: login.php');
    exit;
}

// Generate a CSRF token if one does not already exist.
if (empty($_SESSION['csrf_token'])) {
    $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
}

$error = '';

try {
    // Retrieve the user's current account and MFA information.
    $stmt = $pdo->prepare(
        'SELECT
            user_id,
            login_identifier,
            full_name,
            role,
            mfa_enabled,
            mfa_secret
         FROM users
         WHERE user_id = :user_id
           AND role = :role
           AND is_active = 1
         LIMIT 1'
    );

    $stmt->execute([
        'user_id' => $_SESSION['pending_mfa_user_id'],
        'role' => $_SESSION['pending_mfa_role']
    ]);

    $user = $stmt->fetch(PDO::FETCH_ASSOC);

    // Stop the login process if the account is unavailable.
    if (!$user) {
        session_unset();
        session_destroy();

        header('Location: login.php');
        exit;
    }

    // Users must configure MFA before they can verify a code.
    if (
        (int) $user['mfa_enabled'] !== 1 ||
        empty($user['mfa_secret'])
    ) {
        header('Location: setup_mfa.php');
        exit;
    }

    // Process the submitted verification code.
    if ($_SERVER['REQUEST_METHOD'] === 'POST') {
        $csrf = $_POST['csrf_token'] ?? '';
        $code = trim($_POST['verification_code'] ?? '');

        // Validate the CSRF token.
        if (
            !is_string($csrf) ||
            !hash_equals($_SESSION['csrf_token'], $csrf)
        ) {
            $error = 'Invalid request. Please refresh the page and try again.';
        } elseif (!preg_match('/^\d{6}$/', $code)) {
            $error = 'Please enter all six digits of your verification code.';
        } else {
            $tfa = new TwoFactorAuth(
                new BaconQrCodeProvider(format: 'svg'),
                'EduSphere'
            );

            // Verify the code generated by the authenticator app.
            if (!$tfa->verifyCode($user['mfa_secret'], $code)) {
                $error = 'Invalid verification code. Check your authenticator app and try again.';
            } else {
                // MFA verification is successful.
                session_regenerate_id(true);

                // Establish the authenticated user session.
                $_SESSION['user_id'] = $user['user_id'];
                $_SESSION['login_identifier'] = $user['login_identifier'];
                $_SESSION['full_name'] = $user['full_name'];
                $_SESSION['role'] = $user['role'];
                $_SESSION['auth_complete'] = true;

                // Remove temporary login information.
                unset(
                    $_SESSION['pending_mfa_user_id'],
                    $_SESSION['pending_mfa_role'],
                    $_SESSION['pending_mfa_secret'],
                    $_SESSION['csrf_token']
                );

                // Redirect the user according to their role.
                if ($user['role'] === 'student') {
                    header('Location: student_dashboard.php');
                    exit;
                }

                if ($user['role'] === 'lecturer') {
                    header('Location: lecturer_dashboard.php');
                    exit;
                }

                if ($user['role'] === 'admin') {
                    header('Location: admin_dashboard.php');
                    exit;
                }

                // Reject any unexpected role.
                session_unset();
                session_destroy();

                header('Location: login.php');
                exit;
            }
        }
    }

} catch (Throwable $e) {
    // Record the error privately instead of exposing system details.
    error_log((string) $e);

    http_response_code(500);
    exit('A system error occurred. Please try again later.');
}
